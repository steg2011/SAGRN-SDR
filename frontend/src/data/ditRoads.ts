// Waze prefixes route-numbered roads like "A1 - Princes Hwy"; numbered routes are state roads.
const ROUTE_PREFIX = /^[ABM]\d+\s*-\s*/i;

export function isDitRoad(address: string | null): boolean {
  if (!address) return false;
  const trimmed = address.trim();
  if (ROUTE_PREFIX.test(trimmed)) return true;
  const name = trimmed.toUpperCase().replace(/\s+/g, ' ');
  return DIT_ROAD_NAMES.has(name);
}
